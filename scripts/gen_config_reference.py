"""Write docs/reference/configuration.md from the configuration models.

    python scripts/gen_config_reference.py          # rewrite the file
    python scripts/gen_config_reference.py --check  # fail if it is out of date (CI)
"""

from __future__ import annotations

import argparse
import json
import sys
import typing
from pathlib import Path

from pydantic import BaseModel

from aurora.config import AuroraConfig

OUT = Path(__file__).resolve().parent.parent / "docs" / "reference" / "configuration.md"
LONG_TEXT = 120


def type_name(annotation) -> str:
    text = str(annotation).replace("typing.", "").replace("aurora.config.", "")
    origin = typing.get_origin(annotation)
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return "section"
    if origin is typing.Literal:
        return " \\| ".join(f"`{a}`" for a in typing.get_args(annotation))
    if isinstance(annotation, type) and hasattr(annotation, "__members__"):
        return " \\| ".join(f"`{m.value}`" for m in annotation)
    return text.replace("<class '", "").replace("'>", "")


def default_text(field) -> str:
    if field.is_required():
        return "**required**"
    value = field.get_default(call_default_factory=True)
    if isinstance(value, BaseModel):
        return ""
    if hasattr(value, "value"):
        value = value.value
    text = json.dumps(value, ensure_ascii=False)
    if len(text) > LONG_TEXT:
        return "*(long text, see `aurora init` or the source)*"
    return f"`{text}`"


def section(model: type[BaseModel], prefix: str, lines: list[str]) -> None:
    rows, subs = [], []
    for name, field in model.model_fields.items():
        ann = field.annotation
        if isinstance(ann, type) and issubclass(ann, BaseModel):
            subs.append((name, ann))
            continue
        rows.append(f"| `{prefix}{name}` | {type_name(ann)} | {default_text(field)} | "
                    f"{(field.description or '').replace('|', '\\|')} |")
    if rows:
        lines += ["| Key | Type | Default | Meaning |", "|---|---|---|---|", *rows, ""]
    for name, sub in subs:
        lines += [f"## `{prefix}{name}`", "", (sub.__doc__ or "").strip().split("\n\n")[0], ""]
        section(sub, f"{prefix}{name}.", lines)


def render() -> str:
    lines = [
        "# Configuration reference",
        "",
        "<!-- generated by scripts/gen_config_reference.py; do not edit by hand -->",
        "",
        "A campaign is configured by one YAML file. Only `objective` is required.",
        "Unknown keys are an error. Paths in the file are relative to the file.",
        "`aurora init` writes a commented starter file.",
        "",
        "## Top level",
        "",
    ]
    section(AuroraConfig, "", lines)
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    text = render()
    if ap.parse_args().check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is out of date; run python scripts/gen_config_reference.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
